router = APIRouter(prefix="/api/applications", tags=["applications"])

STORAGE = Path(__file__).resolve().parents[2] / "storage"
SIGNATURES = STORAGE / "signatures"


class CreateRequest(BaseModel):
    program_code: str


class PatchRequest(BaseModel):
    form1: dict[str, Any] | None = None
    self_check: dict[str, Any] | None = None
    form5: dict[str, Any] | None = None


class SelfCheckRequest(BaseModel):
    answers: dict[str, str]


class ConsentItem(BaseModel):
    consent_type: str
    agreed: bool
    #: 서식5 전자서명 data URL (data:image/png;base64,...)
    signature_data_url: str | None = None
    #: electronic | handwritten
    signature_kind: str | None = None


class ConsentRequest(BaseModel):
    consents: list[ConsentItem]


class IdentityRequest(BaseModel):
    name: str
    #: YYYY-MM-DD
    birth: str
    phone: str
    #: "본인이 맞으며, 타인 서류·허위 제출 시 불이익에 동의합니다"
    pledge: bool
    #: 서약 서명 data URL. 직접 그린 서명이면 PNG, 파일로 올리면 PNG·JPG·PDF.
    signature_data_url: str
    #: electronic(화면에 직접 서명) | uploaded(서명 파일 올리기)
    signature_kind: str = "electronic"


#: 본인인증 방식. 실서비스는 로그인 시 PASS·간편인증 결과를 받으므로 이 값이 바뀐다.
IDENTITY_METHOD = "demo"

#: 서약 서명으로 받는 파일 형식 → 저장 확장자. 직접 그린 서명은 PNG만 온다.
SIGNATURE_TYPES = {"image/png": "png", "image/jpeg": "jpg", "application/pdf": "pdf"}
SIGNATURE_MAX_BYTES = 5 * 1024 * 1024
SERVER_FORM_DATE_KEYS = frozenset({
    "writtenMonth", "writtenDay", "writtenOn",
    "job.applicationMonth", "job.applicationDay",
    "consent.form3.year", "consent.form3.month", "consent.form3.day",
    "consent.form4.year", "consent.form4.month", "consent.form4.day",
    "consent.job.year", "consent.job.month", "consent.job.day",
})


def _without_server_form_dates(values: dict[str, Any]) -> dict[str, Any]:
    """Form dates are generated by the server and never persisted from client input."""
    return {key: value for key, value in values.items() if key not in SERVER_FORM_DATE_KEYS}


def _validate_period_dates(values: dict[str, Any]) -> None:
    """거주·근로 기간 산정 날짜는 오늘보다 미래일 수 없다."""
    from ..forms.values import today

    for key in ("transferIn", "employedAt"):
        raw = values.get(key)
        if not raw:
            continue
        if isinstance(raw, dict) and not all(raw.get(part) for part in ("y", "m", "d")):
            continue
        try:
            if isinstance(raw, dict):
                parsed = date(int(raw["y"]), int(raw["m"]), int(raw["d"]))
            else:
                parsed = date.fromisoformat(str(raw))
        except (KeyError, TypeError, ValueError):
            raise HTTPException(400, "기간 산정 날짜 형식을 확인해 주세요.") from None
        if parsed > today():
            raise HTTPException(400, "기간 산정 날짜는 오늘 이후일 수 없습니다.")


def _decode_signature(data_url: str, kind: str) -> tuple[bytes, str]:
    """서명 data URL → (바이트, 확장자). 형식·크기가 맞지 않으면 400."""
    if kind not in ("electronic", "uploaded"):
        raise HTTPException(400, "서명 방식을 확인해 주세요.")
    head, sep, payload = data_url.partition(",")
    if not sep or not head.startswith("data:") or not head.endswith(";base64"):
        raise HTTPException(400, "서약란에 서명해 주세요.")
    mime = head[len("data:"): -len(";base64")]
    allowed = {"image/png"} if kind == "electronic" else set(SIGNATURE_TYPES)
    if mime not in allowed:
        raise HTTPException(400, "서명 파일은 PNG·JPG·PDF만 올릴 수 있습니다.")
    try:
        raw = base64.b64decode(payload, validate=True)
    except ValueError:
        raise HTTPException(400, "서명 파일을 읽을 수 없습니다.") from None
    if not raw:
        raise HTTPException(400, "서약란에 서명해 주세요.")
    if len(raw) > SIGNATURE_MAX_BYTES:
        raise HTTPException(400, "서명 파일은 5MB 이하로 올려 주세요.")
    return raw, SIGNATURE_TYPES[mime]


def _ymd(d: date) -> dict[str, str]:
    """서식1의 년·월·일 3분할 입력 형태."""
    return {"y": str(d.year), "m": str(d.month), "d": str(d.day)}


def _lock_identity(form1: dict[str, Any], identity: dict[str, Any]) -> dict[str, Any]:
    """신청서의 성명·생년월일을 본인인증 값으로 고정한다.

    화면에서 칸을 잠그는 것만으로는 부족하다 — API를 직접 부르면 바꿀 수 있다.
    신청 도중 성명을 바꿔 남의 서류에 맞추는 것을 서버에서 막는다.
    """
    if not identity:
        return form1
    locked = dict(form1)
    locked["name"] = identity["name"]
    locked["birth"] = _ymd(date.fromisoformat(identity["birth"]))
    return locked


def _next_application_no(program_code: str) -> str:
    """APP-2026-000001 형태. 데모라 단순 증가면 충분하다."""
    with get_session() as s:
        count = len(s.exec(select(Application)).all())
    prefix = "DS" if program_code == "double_savings" else "JP"
    return f"{prefix}-2026-{count + 1:06d}"


def _load(application_id: int) -> Application:
    with get_session() as s:
        app = s.get(Application, application_id)
        if app is None:
            raise HTTPException(404, "신청 건을 찾을 수 없습니다.")
        return app


def _require_draft(app: Application) -> None:
    if app.status != STATUS_DRAFT:
        raise HTTPException(409, "제출한 신청서는 수정할 수 없습니다.")


@router.post("")
def create(body: CreateRequest) -> dict[str, Any]:
    get_program(body.program_code)  # 잘못된 사업 코드면 여기서 걸린다
    app = Application(
        application_no=_next_application_no(body.program_code),
        program_code=body.program_code,
        criteria_version=latest_criteria(body.program_code).version,
    )
    with get_session() as s:
        s.add(app)
        s.commit()
        s.refresh(app)
    return app.model_dump()


@router.get("/{application_id}")
def read(application_id: int) -> dict[str, Any]:
    return _load(application_id).model_dump()


@router.patch("/{application_id}")
def patch(application_id: int, body: PatchRequest) -> dict[str, Any]:
    """단계별 부분 저장. 서류 발급하러 이탈했다 돌아올 수 있어야 한다."""
    with get_session() as s:
        app = s.get(Application, application_id)
        if app is None:
            raise HTTPException(404, "신청 건을 찾을 수 없습니다.")
        _require_draft(app)
        if body.form1 is not None:
            _validate_period_dates(body.form1)
            app.form1_json = _lock_identity(_without_server_form_dates(body.form1), app.identity_json or {})
        if body.self_check is not None:
            app.self_check_json = body.self_check
        if body.form5 is not None:
            app.form5_json = _without_server_form_dates(body.form5)
        app.updated_at = datetime.now()
        s.add(app)
        s.commit()
        s.refresh(app)
        return app.model_dump()


@router.post("/{application_id}/identity")
def verify_identity(application_id: int, body: IdentityRequest) -> dict[str, Any]:
    """본인인증 (데모).

    실서비스는 로그인할 때 PASS·간편인증으로 성명·생년월일·CI를 받는다. 데모는 그 단계를
    흉내 내어 입력값을 그대로 인증 결과로 쓴다 — 실연동 시 바꾸는 곳은 이 함수 하나다.
    인증 결과는 신청 건마다 한 번만 정한다. 바꾸려면 새 신청으로 시작한다.
    """
    name = re.sub(r"\s+", "", body.name)
    if not name:
        raise HTTPException(400, "성명을 입력해 주세요.")
    try:
        birth = date.fromisoformat(body.birth)
    except ValueError:
        raise HTTPException(400, "생년월일을 확인해 주세요.") from None
    if birth >= date.today():
        raise HTTPException(400, "생년월일을 확인해 주세요.")
    phone = re.sub(r"\D", "", body.phone)
    if len(phone) != 11 or not phone.startswith("010"):
        raise HTTPException(400, "010으로 시작하는 휴대폰 번호를 입력해 주세요.")
    if not body.pledge:
        raise HTTPException(400, "본인 확인 서약에 동의해 주세요.")
    signature, ext = _decode_signature(body.signature_data_url, body.signature_kind)

    with get_session() as s:
        app = s.get(Application, application_id)
        if app is None:
            raise HTTPException(404, "신청 건을 찾을 수 없습니다.")
        if app.status != STATUS_DRAFT:
            raise HTTPException(409, "이미 제출된 신청입니다.")
        if app.identity_json:
            raise HTTPException(409, "이미 본인인증을 마친 신청입니다. 다른 사람으로 신청하려면 새로 시작해 주세요.")

        SIGNATURES.mkdir(parents=True, exist_ok=True)
        target = SIGNATURES / f"{app.application_no}_identity_pledge.{ext}"
        target.write_bytes(signature)

        app.identity_json = {
            "name": name,
            "birth": birth.isoformat(),
            "phone": f"{phone[:3]}-****-{phone[-4:]}",
            "method": IDENTITY_METHOD,
            "verified_at": datetime.now().isoformat(timespec="seconds"),
            "pledge_signature_path": str(target.relative_to(STORAGE.parent)),
            "pledge_signature_kind": body.signature_kind,
        }
        app.form1_json = _lock_identity(app.form1_json or {}, app.identity_json)
        app.updated_at = datetime.now()
        s.add(app)
        s.commit()
        s.refresh(app)
        return {"identity": app.identity_json, "form1": app.form1_json}


@router.post("/{application_id}/self-check")
def self_check(application_id: int, body: SelfCheckRequest) -> dict[str, Any]:
    """자가진단 채점. 부적격이면 사유와 대안을 함께 돌려준다.

    문항 수는 사업에서 나온다 — 두배적금 8문항, 취업지원패키지 2문항(나이·거주지).
    """
    app = _load(application_id)
    _require_draft(app)
    result = evaluate(body.answers, app.program_code)
    with get_session() as s:
        row = s.get(Application, application_id)
        if row is None:
            raise HTTPException(404, "신청 건을 찾을 수 없습니다.")
        row.self_check_json = dict(body.answers)
        row.updated_at = datetime.now()
        s.add(row)
        s.commit()
    return {
        "eligible": result.eligible,
        "completed": result.completed,
        "failed_item": result.failed_item,
        "reason": result.reason,
        "alternative": result.alternative,
        "total_items": result.total_items,
    }


@router.post("/{application_id}/consents")
def save_consents(application_id: int, body: ConsentRequest, request: Request) -> dict[str, Any]:
    """동의 기록.

    수기 서명 없이도 '누가 언제 무엇에 동의했는지'가 남아야 하므로 시각·IP·UA를
    함께 저장한다. 서식5 전자서명은 PNG로 떨어뜨리고 경로만 DB에 남긴다.
    """
    app = _load(application_id)
    _require_draft(app)
    SIGNATURES.mkdir(parents=True, exist_ok=True)
    saved: list[dict[str, Any]] = []

    with get_session() as s:
        # 같은 신청 건의 기존 동의는 지우고 다시 쓴다 (데모라 이력 관리는 생략).
        for old in s.exec(
            select(Consent).where(Consent.application_id == application_id)
        ).all():
            s.delete(old)

        for item in body.consents:
            signature_path: str | None = None
            if item.signature_data_url and "," in item.signature_data_url:
                raw = base64.b64decode(item.signature_data_url.split(",", 1)[1])
                target = SIGNATURES / f"{app.application_no}_{item.consent_type}.png"
                target.write_bytes(raw)
                signature_path = str(target.relative_to(STORAGE.parent))

            consent = Consent(
                application_id=application_id,
                consent_type=item.consent_type,
                agreed=item.agreed,
                signature_path=signature_path,
                signature_kind=item.signature_kind,
                client_ip=request.client.host if request.client else None,
                user_agent=request.headers.get("user-agent"),
            )
            s.add(consent)
            saved.append(
                {
                    "consent_type": item.consent_type,
                    "agreed": item.agreed,
                    "signature_saved": signature_path is not None,
                }
            )
        s.commit()

    return {"saved": saved}


@router.get("/{application_id}/consents")
def list_consents(application_id: int) -> list[dict[str, Any]]:
    with get_session() as s:
        rows = s.exec(
            select(Consent).where(Consent.application_id == application_id)
        ).all()
        return [r.model_dump() for r in rows]
