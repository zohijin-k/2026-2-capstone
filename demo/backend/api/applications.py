"""신청 CRUD · 임시저장 · 자가진단 · 동의.

P1 범위: 파일 업로드 없이 서식1~5를 끝까지 작성·저장할 수 있게 한다.
서류 업로드와 즉시 판정은 P2, 제출 파이프라인과 채점은 P3에서 붙는다.
"""

